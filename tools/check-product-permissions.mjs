import { strict as assert } from 'node:assert'
import { ADD_ON_CAPABILITIES, CAPABILITIES, ROLES, can } from '../src/core/permissions/roles.js'
import { canPerform, UI_ACTIONS } from '../src/core/actions/actionPolicy.js'

assert.equal(can(ROLES.DEPARTMENT_USER,CAPABILITIES.EDIT_PATIENT),false)
assert.equal(can(ROLES.HOSPITAL_ADMIN,CAPABILITIES.EDIT_PATIENT),true)
assert.equal(can(ROLES.HOSPITAL_ADMIN,CAPABILITIES.DELETE_PATIENT),true)
assert.equal(can(ROLES.INFECTION_CONTROL_LEAD,CAPABILITIES.CREATE_SURVEILLANCE),true)
assert.equal(can(ROLES.DEPARTMENT_MANAGER,CAPABILITIES.CREATE_SURVEILLANCE),false)
assert.equal(can(ROLES.HOSPITAL_ADMIN,CAPABILITIES.MANAGE_ROLES),true)
assert.equal(can(ROLES.HOSPITAL_ADMIN,CAPABILITIES.MANAGE_BED_DAYS),true)
assert.equal(canPerform({role:ROLES.DEPARTMENT_USER,action:UI_ACTIONS.DELETE,resourceCapability:CAPABILITIES.DELETE_PATIENT}),false)
assert.equal(canPerform({role:ROLES.HOSPITAL_ADMIN,action:UI_ACTIONS.DELETE,resourceCapability:CAPABILITIES.DELETE_PATIENT}),true)
assert.equal(canPerform({role:ROLES.HOSPITAL_ADMIN,action:UI_ACTIONS.EDIT,resourceCapability:CAPABILITIES.EDIT_PATIENT,locked:true}),false)
assert.equal(can(ROLES.DEPARTMENT_USER,CAPABILITIES.RECORD_HAND_HYGIENE,[ADD_ON_CAPABILITIES.HAND_HYGIENE_OBSERVER]),true)
assert.equal(can(ROLES.DEPARTMENT_USER,CAPABILITIES.RECORD_WASTE,[ADD_ON_CAPABILITIES.WASTE_MANAGEMENT]),true)
assert.equal(can(ROLES.HR_OFFICE,CAPABILITIES.MANAGE_STAFF_ADMIN),true)
assert.equal(can(ROLES.HR_OFFICE,CAPABILITIES.MANAGE_OCCUPATIONAL_HEALTH),false)
assert.equal(can(ROLES.OCCUPATIONAL_PHYSICIAN,CAPABILITIES.MANAGE_OCCUPATIONAL_HEALTH),true)
assert.equal(can(ROLES.HOSPITAL_ADMIN,CAPABILITIES.MANAGE_OCCUPATIONAL_HEALTH),false)
console.log('Product permission checks passed: 15 assertions.')
